export interface HelpItem {
  title: string;
  subtitle: string;
  description: string;
  tips: string[];
}

export function getContextualHelp(
  role: 'lawyer' | 'client',
  activeNav: string,
  caseTab?: string
): HelpItem {
  if (role === 'client') {
    return {
      title: 'ศูนย์ช่วยเหลือสำหรับลูกความ',
      subtitle: 'พื้นที่ส่งเอกสารและติดตามความคืบหน้าของคดีกับทนายความ',
      description: 'ท่านสามารถดูรายการเอกสารที่ทนายความร้องขอ และอัปโหลดไฟล์หลักฐานได้สะดวกรวดเร็วในหน้าเดียว',
      tips: [
        'กดปุ่ม "+ ส่งเอกสาร" เพื่ออัปโหลดไฟล์รูปภาพ สัญญา หรือสลิป',
        'เมื่อส่งแล้ว สถานะจะเปลี่ยนเป็น "กำลังตรวจ" เพื่อให้ทนายตรวจสอบ',
        'สามารถอ่านข้อความและการแจ้งเตือนจากทนายความได้ที่แถบข้อความ',
        'หากต้องการสอบถามเพิ่มเติม สามารถพิมพ์ส่งข้อความถึงทนายความได้โดยตรง',
      ],
    };
  }

  // Lawyer role contextual help
  if (activeNav === 'dashboard') {
    return {
      title: 'หน้าหลักทนายความ (Dashboard)',
      subtitle: 'โฟกัส 3 สิ่งสำคัญ: งานวันนี้, Deadline ใกล้ถึง, และเอกสารรอตรวจ',
      description: 'ออกแบบให้เรียบง่าย ไม่ซับซ้อน ช่วยให้เห็นภาระงานสำคัญที่สุดทันทีที่เปิดระบบ',
      tips: [
        'กด "+ สร้างคดีใหม่" เพื่อเปิดแฟ้มคดีใหม่ได้ทันที',
        'คลิกที่การ์ดคดีเพื่อเข้าสู่พื้นที่จัดการคดีแบบละเอียด',
        'ตรวจเอกสารที่ลูกความส่งเข้ามาได้โดยตรงจากช่องเอกสารรอตรวจ',
      ],
    };
  }

  if (activeNav === 'cases' && caseTab === 'mindmap') {
    return {
      title: 'Mind Map เชื่อมโยงเหตุการณ์',
      subtitle: 'เชื่อมโยงเหตุการณ์ บุคคล และเอกสารหลักฐานให้เห็นภาพรวมของคดี',
      description: 'Mind Map ใช้สำหรับเชื่อมโยงเหตุการณ์ บุคคล และหลักฐานเข้าด้วยกัน ทำให้เข้าใจภาพรวมเรื่องราวได้อย่างเป็นรูปธรรม',
      tips: [
        'คลิกที่ Node เพื่อดูรายละเอียดและแก้ไขข้อมูลในแถบด้านข้าง',
        'ใช้ปุ่ม "✨ จัดโครงสร้างด้วย AI" เพื่อนำคำบอกเล่าของลูกความมาสร้างเป็นโครงสร้างคดีอัตโนมัติ',
        'สามารถเลื่อน (Pan) และซูม (Zoom) ผืนผ้าใบได้อย่างอิสระ',
        'AI ในระบบมีหน้าที่จัดระเบียบข้อมูลเท่านั้น ไม่มีการวิเคราะห์หรือชี้ขาดผลทางกฎหมาย',
      ],
    };
  }

  if (activeNav === 'cases' && caseTab === 'timeline') {
    return {
      title: 'Timeline ลำดับเหตุการณ์ตามเวลา',
      subtitle: 'Timeline แสดงเหตุการณ์ตามวันที่ เกิดอะไรขึ้นก่อนและหลัง',
      description: 'ช่วยให้เห็นลำดับเรื่องราวอย่างชัดเจน ป้องกันการสับสนเรื่องอายุความหรือลำดับการกระทำ',
      tips: [
        'กดปุ่ม "+ เพิ่มเหตุการณ์" โดยระบบจะถามทีละขั้นตอนเพื่อความสะดวก',
        'คลิกที่เหตุการณ์เพื่อดูบุคคลหรือเอกสารที่เชื่อมโยงอยู่',
        'เหตุการณ์จะถูกจัดเรียงตามวันที่อย่างเป็นระเบียบ',
      ],
    };
  }

  if (activeNav === 'cases' && caseTab === 'checklist') {
    return {
      title: 'Checklist ตรวจสอบเอกสาร',
      subtitle: 'Checklist ใช้ตรวจสอบว่าเอกสารใดส่งแล้วหรือยังขาด',
      description: 'แบ่งออกเป็น 2 ฝั่งชัดเจน: ฝั่งที่ลูกความต้องส่ง และฝั่งที่ทนายความต้องตรวจสอบ',
      tips: [
        'คลิกเครื่องหมายถูกเพื่อเปลี่ยนสถานะเป็น "ตรวจแล้ว"',
        'ดูสรุปจำนวนเอกสารที่เสร็จสิ้นได้จากแถบด้านบน (เช่น 6 จาก 8 รายการเสร็จแล้ว)',
        'ช่วยป้องกันการตกหล่นของพยานหลักฐานสำคัญก่อนยื่นฟ้องหรือขึ้นศาล',
      ],
    };
  }

  if (activeNav === 'cases' && caseTab === 'documents') {
    return {
      title: 'คลังเอกสารของคดี (Documents)',
      subtitle: 'รวบรวมไฟล์หลักฐานและเอกสารประกอบคดีทั้งหมด',
      description: 'จัดระเบียบเอกสารตามประเภท เช่น สัญญา, บัตรประชาชน, สลิปโอนเงิน, แชท, และหนังสือแจ้งเตือน',
      tips: [
        'สามารถกรองดูเอกสารตามสถานะ "กำลังตรวจ" หรือ "ตรวจแล้ว"',
        'กดดูรายละเอียดของเอกสารเพื่อตรวจสอบความถูกต้องและบันทึกเพิ่มเติม',
      ],
    };
  }

  // Default Overview
  return {
    title: 'ภาพรวมคดี (Case Overview)',
    subtitle: 'สรุปภาพรวมสำคัญ: จำนวนเหตุการณ์ เอกสาร บุคคล และสิ่งที่ต้องทำต่อ',
    description: 'หน้านี้ช่วยตอบคำถามว่า "ตอนนี้ผู้ใช้ควรทำอะไรต่อ" โดยสรุปสถานะปัจจุบันและสิ่งที่ต้องดำเนินการถัดไป',
    tips: [
      'ดูตัวเลขสถิติของคดี: เหตุการณ์, เอกสาร, บุคคล, และความคืบหน้า Checklist',
      'เช็กรายการ "สิ่งที่ต้องทำต่อ" เพื่อเตรียมคดีอย่างเป็นระบบ',
      'สลับไปยังแท็บ Mind Map, Timeline, เอกสาร หรือ Checklist จากแถบด้านบน',
    ],
  };
}
